/**
 * Правила AntiCringe: инфобизнес-клише, канцелярит, вода, маркеры логических ошибок.
 * Каждое правило — реальная проверка по тексту, а не заглушка.
 *
 * Синтаксис шаблонов:
 *   `%` — любое русское окончание ([а-яё]*)
 *   `#` — число
 *   `_` — разделитель между словами (пробел, запятая, тире)
 *   `%%` — литеральный знак процента
 *   `<а~б>` — выбор одной из форм
 * Границы слова добавляются автоматически.
 *
 * fix: строка замены ('' — удалить фрагмент). Если fix не задан — правка только ручная.
 * mode: что именно удалять — 'word' (по умолчанию), 'lead' (слово вместе с запятой),
 *       'clause' (до конца оборота), 'sentence' (всё предложение).
 */

const LETTER = '[а-яёa-z]'

/** Компилирует человекочитаемый шаблон в регулярное выражение. */
export function compile(pattern) {
  const body = pattern
    .replace(/%%/g, '\u0000')
    .replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    .replace(/%/g, '[а-яё]*')
    .replace(/#/g, '\\d+')
    .replace(/_/g, '[\\s,\u2014\u2013-]+')
    .replace(/</g, '(?:')
    .replace(/>/g, ')')
    .replace(/~/g, '|')
    .replace(/\u0000/g, '%')
  return new RegExp(`(?<!${LETTER})${body}(?!${LETTER})`, 'giu')
}

